#1
# Менеджер завдань (консольна програма) + workflow роботи з AI
#
# 1. Аналіз задачі (самостійно)
#    - Дані: список завдань (рядки) зберігаємо в пам'яті, у list.
#    - Меню в циклі: 1 - додати, 2 - показати, 3 - видалити, 4 - вихід.
#    - Додавання: не можна додати порожнє завдання (або з одних пробілів).
#    - Показ: якщо список порожній - вивести повідомлення, інакше пронумерований список.
#    - Видалення: за номером; треба перевіряти, що ввели число і що такий номер існує.
#    - Неправильний пункт меню - повідомлення про помилку, програма не падає.
#
# 2. Prompt
#    "Напиши консольну програму на Python 'Менеджер завдань'. Меню в циклі:
#    1 - додати завдання, 2 - показати всі, 3 - видалити за номером, 4 - вихід.
#    Перевіряй неправильний вибір у меню. Розбий код на функції, коментарі українською."
#
# 3-4. Рішення AI і читання коду
#    AI дав робочу версію з функціями add/show/delete і циклом while True.
#    Під час читання помітив: при видаленні використовувався int(input()) без try/except,
#    і номер не перевірявся на межі списку; порожнє завдання можна було додати.
#
# 5-6. Запуск і test cases (див. також функцію run_tests() нижче)
#    TC1: вибір "5" або "abc" у меню -> "Невірний вибір", програма працює далі.     OK
#    TC2: додати "Купити хліб" і показати -> "1. Купити хліб".                       OK
#    TC3: видалити "abc" -> до виправлення: ValueError, програма падала.             FAIL
#    TC4: видалити номер 10 при 1 завданні -> до виправлення: IndexError.            FAIL
#    TC5: видалити номер 0 -> до виправлення видалявся ОСТАННІЙ елемент (tasks[-1]). FAIL
#    TC6: додати порожній рядок -> до виправлення додавалось порожнє завдання.       FAIL
#    TC7: показати порожній список -> "Список завдань порожній".                     OK
#
# 7. Follow-up prompt
#    "У функції видалення програма падає, якщо ввести не число (ValueError) або номер,
#    якого немає (IndexError), а номер 0 видаляє останнє завдання. Також можна додати
#    порожнє завдання. Виправ: перевіряй, що номер - ціле число від 1 до кількості
#    завдань, і не дозволяй додавати порожні завдання."
#    Після цього AI додав try/except ValueError, перевірку 1 <= number <= len(tasks)
#    і .strip() для тексту завдання. Повторний запуск - усі test cases OK.
#
# 8. Пояснення коду своїми словами
#    - tasks - звичайний список рядків, усі функції працюють з ним.
#    - add_task() прибирає пробіли по краях і додає завдання, якщо воно не порожнє.
#    - show_tasks() виводить завдання з номерами, починаючи з 1 (enumerate(..., 1)).
#    - delete_task() перетворює введене на int у try/except, перевіряє межі
#      і видаляє через pop(number - 1), бо користувач рахує з 1, а список - з 0.
#    - main() - нескінченний цикл з меню; "4" робить break, будь-що інше,
#      крім 1-4, потрапляє в else і виводить помилку.
#    - Функції повертають рядок-повідомлення, а print робиться в main(),
#      тому їх легко перевірити тестами без введення з клавіатури.


def add_task(tasks, text):
    text = text.strip()
    if not text:
        return "Помилка: завдання не може бути порожнім"
    tasks.append(text)
    return f"Завдання '{text}' додано"


def show_tasks(tasks):
    if not tasks:
        return "Список завдань порожній"
    lines = [f"{i}. {task}" for i, task in enumerate(tasks, 1)]
    return "\n".join(lines)


def delete_task(tasks, number_text):
    if not tasks:
        return "Список завдань порожній, нічого видаляти"
    try:
        number = int(number_text)
    except ValueError:
        return "Помилка: потрібно ввести число"
    if number < 1 or number > len(tasks):
        return f"Помилка: завдання з номером {number} не існує"
    removed = tasks.pop(number - 1)
    return f"Завдання '{removed}' видалено"


def main():
    tasks = []
    while True:
        print("\n--- Менеджер завдань ---")
        print("1 - Додати завдання")
        print("2 - Показати всі завдання")
        print("3 - Видалити завдання")
        print("4 - Вихід")
        choice = input("Ваш вибір: ").strip()

        if choice == "1":
            print(add_task(tasks, input("Введіть завдання: ")))
        elif choice == "2":
            print(show_tasks(tasks))
        elif choice == "3":
            print(show_tasks(tasks))
            if tasks:
                print(delete_task(tasks, input("Номер завдання для видалення: ")))
        elif choice == "4":
            print("До побачення!")
            break
        else:
            print("Невірний вибір, введіть число від 1 до 4")


def run_tests():
    tasks = []
    assert show_tasks(tasks) == "Список завдань порожній"
    assert add_task(tasks, "   ") == "Помилка: завдання не може бути порожнім"
    assert tasks == []
    add_task(tasks, "  Купити хліб ")
    add_task(tasks, "Зробити ДЗ")
    assert show_tasks(tasks) == "1. Купити хліб\n2. Зробити ДЗ"
    assert delete_task(tasks, "abc") == "Помилка: потрібно ввести число"
    assert delete_task(tasks, "10") == "Помилка: завдання з номером 10 не існує"
    assert delete_task(tasks, "0") == "Помилка: завдання з номером 0 не існує"
    assert delete_task(tasks, "1") == "Завдання 'Купити хліб' видалено"
    assert tasks == ["Зробити ДЗ"]
    print("Усі тести пройдено")


if __name__ == "__main__":
    run_tests()
    main()
